The task was gargantuan, and no mere mortal man could have faced it without going mad. Guilliman offered leadership and hope, and he became a figurehead for the reborn Imperium. Countless billions came to know his name, and while he could never replace their beloved Emperor, Guilliman was a firm hand when it was needed most, and the Imperium endured.

In committing his wisdom to the first volumes of the Codex Astartes, Guilliman must have known that he would not see his most cherished ambitions fulfilled. After all, none had ever imagined that a primarch might know death, but the Horus Heresy had seen several slain or otherwise lost, and in the years that followed more would suffer similar fates.

When Guilliman was lost to the Imperium, he left behind him countless works of wisdom and insight, and the greatest of these was the Codex Astartes. Though the Imperium would again rise to heights rivalling those of the Great Crusade, and descend to depths of despair as dark as the Horus Heresy, Roboute Guilliman's wisdom would prevail.

The Ultramarines were and are the guardians of that wisdom, and the exemplars of all their primarch embodied. The Codex Astartes has become a sacred text for them, a blueprint describing the ideals by which the majority of Chapters organise themselves, fight, recruit, train and operate.

The Ultramarines rule over a region of space called Ultramar, an autonomous realm that owes no tithes to the Imperium and looks entirely to its own defence. The peoples of the various worlds of Ultramar look to the Ultramarines as both beneficent rulers and as distant figures of legend. While the vast majority of Humanity will never even see a Space Marine, let alone speak to one, the people of Ultramar are more familiar with these mighty warriors. Some even have the honour of being distantly related to one, perhaps some distant ancestor having been accepted into the Chapter. The Ultramarines regard it as their sacred duty to rule their domains justly, and to protect them as the source of their recruiting and resources. In this the Ultramarines are continuing the legacy of their primarch, whose teachings each warrior studies and memorises over the course of his service.

The Codex Astartes is such a vast body of wisdom that even the prodigious, genetically-enhanced mental capacity of a Space Marine is taxed with absorbing it all. Yet the Ultramarines regard it as their duty to do so, and choose to eschew the blunt tool of psycho-conditioning in favour of learning every passage by remorseless study.

Each battle-brother absorbs and analyses entire chapters of the Codex, so that after several standard centuries of service he is at once a master and a scholar of his chosen area of expertise. Within a company, especially a low-numbered one consisting of numerous long-service Veterans, it is likely that the entire Codex Astartes will be known by the battle-brothers, allowing its commanding captain to draw upon an enormous pool of wisdom as well as experience. A Veteran Ultramarines battle-brother is therefore a deeply learned individual, schooled in every nuance of the arts of war and the wisdom of his primarch.
