        <h2>The Ultramarines</h2>
        <p>
            Highly-disciplined and courageous warriors, the Ultramarines have remained true to the teachings of Primarch Roboute Guilliman for 10,000 standard years. The Ultramarines were originally the XIIIth Space Marine Legion before the reforms that initiated the Second Founding and reshaped the Imperium after the Heresy in the Time of Rebirth on the orders of Guilliman himself as the Lord Commander of the Imperium and Imperial Regent.

The name "Ultramarines" is a nod to the Chapter's galactic region of origin, its standing amongst the other Space Marine Chapters and their role as the source for the gene-seed of more Chapters of the Adeptus Astartes than any of the other former First Founding Legions combined.

The culture of the Ultramarines is loosely themed upon the culture of Old Earth's ancient Roman Empire, as exemplified in their Astartes' High Gothic names and their strict adherence to the Codex Astartes, as well as the society of their homeworld of Macragge and the Chapter's method of recruitment.

The Ultramarines directly rule the sub-sector of space in the Segmentum Ultima of the galactic east known as Ultramar as a fief of the Imperium and their Chapter Master is also considered the Lord of Macragge and the Master of Ultramar.

Of all the thousand and more Space Marine Chapters in the Imperium, it is the blue-clad Ultramarines that, in the mind of the countless billions of the Emperor's subjects, personify everything that the Adeptus Astartes stands for. The Ultramarines and their many Successor Chapters have stood at the very forefront of the war against the Traitor, the alien, and the Daemon since the very foundation of the Imperium. Across the domains of the Emperor, the Ultramarines are celebrated as heroic, virtuous, and noble defenders of Humanity, their deeds recorded in devotional works the length and breadth of the galaxy.

Even amongst the Space Marine Chapters themselves, the Ultramarines occupy a position of special honour. The gene-seed from which the original Ultramarines Legion was founded is considered the purest that remains, and it is estimated that some two-thirds of Chapters across the galaxy share their inheritance, being either direct successors or created from tithed Ultramarines genetic material. This shared inheritance often ensures that when the Ultramarines go to war, they are supported by many other Chapters, and that when Space Marine commanders gather to consider common strategy, the counsel of the Ultramarines is greatly valued.

Often, the presence of even a small number of Ultramarines units in a larger military undertaking will ensure the participation of many more Chapters, so highly are the sons of Roboute Guilliman held in their brothers' esteem.

When Hive Fleet Behemoth struck the Eastern Fringe, it was the Ultramarines Chapter that turned the tide, even at the cost of the Chapter's entire Veteran 1st Company. At the Chapter homeworld of Macragge, one of the largest battles seen in centuries was fought, with the Ultramarines, led by their master Marneus Calgar, at the very forefront. In addition to the great honour won by the Chapter in that titanic struggle, the Ultramarines gained invaluable experience in fighting these vile xenos, which they have passed on, often via service in the Deathwatch, to many other Chapters.

When the Horus Heresy erupted, the Ultramarines were long prevented from defending the Throneworld by the great Ruinstorm conjured by the Word Bearers during the Battle of Calth that cut the galaxy in half for long years. By the time the Ruinstorm dissipated and the Ultramarines could move to reinforce Terra, the Warmaster Horus' Siege of Terra was already underway.

Nevertheless, the Ultramarines fought their way towards Terra, and although they defeated a massive Traitor space ﬂeet, were unable to reach the Sol System in time to intervene in the final battle. It is Guilliman's actions subsequent to the Horus Heresy that made him the figure of adoration that he would become. With the Traitors scattered and the Emperor to all intents and purposes lost to Humanity, the Imperium stood at the precipice.

