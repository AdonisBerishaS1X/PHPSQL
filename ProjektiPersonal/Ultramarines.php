It was the genius and leadership of Roboute Guilliman that saw the Imperium through its first standard century after the Heresy, as he kept invaders at bay and saved the scattered Human worlds from collapsing into anarchy, reforming the Imperial bureaucracy and armed forces as needed.

Roboute Guilliman fell at the hands of his erstwhile brother, the Daemon Primarch Fulgrim of the Emperor's Children Traitor Legion, at the Battle of Thessala in 121.M31. Poisoned unto death, Guilliman's barely living body was placed in a stasis field, and later enthroned in the Ultramarines' fortress-monastery. There it remained for ten thousand standard years, until he was resurrected by a combination of Imperial science and Aeldari mysticism during the 13th Black Crusade in ca. 999.M41. He would take up the mantle of the Lord Commander of the Imperium and the Imperial Regent once more, and now leads the defence of Mankind from the darkness brought by the birth of the Great Rift at the dawn of the Era Indomitus.

The Ultramarines are by far the best known and most celebrated Adeptus Astartes Chapter in the long and bloody history of the Imperium of Man. Statues of their primarch and their greatest heroes rear high above countless plazas and city gates, and images of their myriad victories glow from stained glass windows in the mightiest basilicas imperialis.

The Ultramarines Legion was the largest of those bodies raised to prosecute the Great Crusade so long ago, and as a result it provided the largest number of Chapters when the Second Founding occurred in the aftermath of the Horus Heresy. In addition, the Chapter's gene-seed is generally held to be the purest of all the Adeptus Astartes, and it is so stable that even 10,000 standard years after its inception, mutation is well within tolerable limits. For this reason, a majority of Space Marines Chapters extant in the 41st Millennium are thought to be related to the Ultramarines, whether either is aware of it or not, and as such, inheritors of all that made that Legion so great.

The Ultramarines Chapter is at once the exemplar of everything a Space Marine aspires to, and the template by which he acts, fights and worships. Every Chapter has its own traditions, histories and battle-honours, but the Ultramarines are the standard by which many others, especially those of their genetic lineage, judge themselves and their peers, whether they acknowledge it or not.

It is through the dictates of the Codex Astartes that the 10,000 Terran years of wisdom and expertise gleaned by the Ultramarines are enshrined. This vast reserve of lore was authored by the Ultramarines primarch, Roboute Guilliman himself, wherein he laid the foundations of the Imperium's reformation during the Time of Rebirth in the aftermath of the calamitous wars of the Horus Heresy. Guilliman was a leader of prodigious intellect, and not just in the military fields. With the Imperium brought to its knees by galactic civil war, he turned his mind to uniting and codifying the highest echelons of the Imperium's government, imposing order on institutions that had been split asunder by the anarchy of the Heresy. Only a primarch, a gene-son of the Emperor Himself, could have conceived such an undertaking, for the scattered Imperial worlds that had survived the Heresy were on their knees, riven with plague and famine and rife for rebellion or invasion.

